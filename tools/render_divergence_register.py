#!/usr/bin/env python3
"""Render spec/divergence-register.yaml as spec/divergence-register.md, and refuse drift.

The register is the governed record and the rendering is its human-readable
form (`docs/THE-GAMEPLAN.md` section 2.1). This tool is the only writer of
`spec/divergence-register.md`. A hand edit to the rendering is drift, and
`--check` renders in memory, compares the result with the file on disk, and
refuses on any difference, the way `tools/generate_pse.py --check` does for the
generated schema. `tools/validate_divergence_register.py` runs the same
comparison on every run of the gate, so a stale rendering refuses in the hook
and in the kernel gate as well as here.

The rendering is built from three sources and nothing else: the register, the
diff `tools/validate_divergence_register.py` derives from the two schemas, and
the two conformance corpora, which give each test_ref its line number. Nothing
volatile enters it, such as a file count of the tree, so it moves only when one
of the three moves.

Exit codes: 0 written or current, 1 the rendering is stale or missing under
--check, 2 an input could not be read.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import validate_divergence_register as vdr  # noqa: E402

TOOL = "tools/render_divergence_register.py"

CLASS_LABELS = (
    ("zmeta", f"in {vdr.ZSIDE} only"),
    ("pse", f"in {vdr.PSIDE} only"),
    ("differs", "in both, differing"),
    ("identical", "in both, identical"),
)


def _cell(value) -> str:
    text = " ".join(str(value if value is not None else "").split())
    return text.replace("|", "\\|")


def _text(value) -> str:
    return " ".join(str(value if value is not None else "").split())


def _code(value) -> str:
    return f"`{_text(value)}`"


def _covers(paths: list, classes: dict) -> str:
    parts = []
    for key, label in CLASS_LABELS:
        n = sum(1 for p in paths if classes.get(p) == key)
        if n:
            parts.append(f"{n} {label}")
    return ", ".join(parts) if parts else "none"


def _short(paths: list, classes: dict) -> str:
    keys = {"zmeta": "ZMeta", "pse": "PSE", "differs": "differing", "identical": "identical"}
    parts = []
    for key, _ in CLASS_LABELS:
        n = sum(1 for p in paths if classes.get(p) == key)
        if n:
            parts.append(f"{keys[key]} {n}")
    return ", ".join(parts) if parts else "policy surface"


def _sections(entry: dict) -> str:
    values = [str(s) for s in vdr._as_list(entry.get("contract"))]
    if not values:
        return "no contract section"
    word = "section" if len(values) == 1 else "sections"
    return f"contract {word} {', '.join(values)}"


def _test_ref(ref: str, ctx: dict) -> str:
    rel, _, name = str(ref).partition("#")
    for n, obj in ctx["corpora"].get(rel, []):
        if isinstance(obj, dict) and obj.get("name") == name:
            expect = obj.get("expect_code")
            tail = f", expects {_code(expect)}" if expect else ", must pass"
            return f"`{rel}` line {n}, fixture {_code(name)}{tail}"
    return f"{_code(ref)}, which resolves to no fixture"


def render(ctx: dict) -> str:
    register = ctx["register"]
    header = register.get("register") if isinstance(register.get("register"), dict) else {}
    upstream = header.get("upstream") if isinstance(header.get("upstream"), dict) else {}
    r = vdr.resolve(ctx)
    classes = r["classes"]
    entries = r["entries"]
    by_owner: dict = {}
    for p, owner in r["cover"].items():
        by_owner.setdefault(owner, []).append(p)
    counts = {key: sum(1 for v in classes.values() if v == key) for key, _ in CLASS_LABELS}

    out: list[str] = []
    w = out.append
    w(f"# Divergence register: {vdr.PSIDE} against {vdr.ZSIDE}")
    w("")
    w(
        f"GENERATED by `{TOOL}` from `spec/divergence-register.yaml`. Never hand-edited: edit the "
        "register and render it again. `--check` refuses a rendering that differs from what the "
        "register renders, and `tools/validate_divergence_register.py` makes the same comparison on "
        "every run of the gate."
    )
    w("")
    w(
        "This rendering is advisory and Class A. The register it renders is rank 3 and Class B, and "
        "where the two disagree the register is the record. PSE is a private dialect derived from "
        f"{vdr.ZSIDE} and claims no upstream compatibility (`AGENTS.md` section 1)."
    )
    if header.get("status"):
        w("")
        w(f"**Status:** {_text(header.get('status'))}")
    w("")
    w("## 1. What the diff found")
    w("")
    zb, pb = ctx.get("zmeta_branches") or [], ctx.get("pse_branches") or []
    shared = sorted(set(zb) & set(pb))
    shared_text = ", ".join(f"{t} {s}" for t, s in shared) if shared else "none"
    w(
        "`tools/validate_divergence_register.py` evaluates each schema once per event type and "
        "subtype it binds and records every pointer an event can carry a value at, with its type, "
        "enum, required-ness, format and pattern, bounds and closure. "
        f"{vdr.ZSIDE} binds {len(zb)} type and subtype pairs and {vdr.PSIDE} binds {len(pb)}, and "
        f"the pairs the two have in common are these: {shared_text}. A payload pointer names the pair "
        "it is read under, and "
        "`*` is every item of an array or every value of an open map."
    )
    w("")
    w("| Class | Pointers | Covered by |")
    w("|---|---|---|")
    w(f"| In {vdr.ZSIDE} only | {counts['zmeta']} | a DROP or REPLACE entry |")
    w(f"| In {vdr.PSIDE} only | {counts['pse']} | a NEW or REPLACE entry |")
    w(f"| In both, differing | {counts['differs']} | a REPLACE or INVERT entry |")
    w(f"| In both, identical | {counts['identical']} | the identical list, or a KEEP entry |")
    w("")
    w(f"- **Upstream schema:** {_code(upstream.get('path'))}, release {_text(upstream.get('release'))}, sha256 {_code(upstream.get('sha256'))} with line endings normalized to LF.")
    w(f"- **Diff last reviewed:** sha256 {_code(header.get('diff_sha256'))}. A change to either schema that moves the diff refuses until the register is reviewed and this pin moves with it.")
    w("")
    w("## 2. Dispositions")
    w("")
    stated = header.get("dispositions") if isinstance(header.get("dispositions"), dict) else {}
    w("| Disposition | Meaning |")
    w("|---|---|")
    for name in vdr.DISPOSITIONS:
        w(f"| {name} | {_cell(stated.get(name, 'not stated in the register'))} |")
    w("")
    w("## 3. Entries")
    w("")
    w("| Entry | Disposition | Title | Cites | Pointers covered |")
    w("|---|---|---|---|---|")
    for i, entry in enumerate(entries):
        if not isinstance(entry, dict):
            continue
        cites = ", ".join(str(d) for d in vdr._as_list(entry.get("divergence"))) or "none"
        w(
            f"| {_cell(entry.get('id'))} | {_cell(entry.get('disposition'))} | {_cell(entry.get('title'))} "
            f"| {_cell(cites)} | {_cell(_short(sorted(by_owner.get(i, [])), classes))} |"
        )
    for i, entry in enumerate(entries):
        if not isinstance(entry, dict):
            continue
        w("")
        w(f"### {_text(entry.get('id'))} {_text(entry.get('title'))}")
        w("")
        w(f"- **Disposition:** {_text(entry.get('disposition'))}")
        cites = ", ".join(str(d) for d in vdr._as_list(entry.get("divergence")))
        w(f"- **Cites:** {cites + '; ' if cites else ''}{_sections(entry)}")
        if entry.get("surface"):
            w(f"- **Surface:** {_code(entry.get('surface'))}")
        pointers = ", ".join(_code(p) for p in vdr._as_list(entry.get("pointers")))
        w(f"- **Pointers:** {pointers or 'none'}")
        if not entry.get("surface"):
            w(f"- **Covers:** {_covers(sorted(by_owner.get(i, [])), classes)}")
        w(f"- **Rationale:** {_text(entry.get('rationale'))}")
        w(f"- **Mechanism preserved:** {_text(entry.get('mechanism_preserved'))}")
        for ref in vdr._as_list(entry.get("test_ref")):
            w(f"- **Test ref:** {_test_ref(ref, ctx)}")
        if entry.get("test_gap"):
            w(f"- **Test gap:** {_text(entry.get('test_gap'))}")
        if entry.get("reading"):
            w(f"- **Reading awaiting the operator:** {_text(entry.get('reading'))}")
    w("")
    w("## 4. Identical")
    w("")
    w(
        "The two schemas agree at these pointers on every compared attribute, and the register lists "
        "them so a reader can tell a pointer that was compared from one nobody looked at."
    )
    w("")
    for pointer in vdr._as_list(register.get("identical")):
        w(f"- {_code(pointer)}")
    w("")
    w("## 5. Readings awaiting the operator")
    w("")
    w(
        "Each reading is a question the agent that drafted the register could not settle from the "
        "contract. None of them is a decision, and an entry that carries one records the reading the "
        "register took until the operator answers."
    )
    w("")
    for rd in vdr._as_list(register.get("readings")):
        if isinstance(rd, dict):
            w(f"- **{_text(rd.get('id'))}.** {_text(rd.get('question'))}")
    with_reading = [str(e.get("id")) for e in entries if isinstance(e, dict) and e.get("reading")]
    if with_reading:
        w(f"- **Entry readings:** {', '.join(with_reading)}, each stated in its entry above.")
    w("")
    w("## 6. The compatibility claim")
    w("")
    w(
        "`tools/validate_divergence_register.py` refuses the upstream compatibility claim in every "
        "tracked file and every untracked file git does not ignore, without regard to case, with the "
        "hyphen written as a hyphen-minus, a hyphen or a non-breaking hyphen. It assembles the string "
        "at run time, so neither the register nor this rendering "
        "carries it. A line is exempt only by its file and the sha256 of its text, so an edit to the "
        "line, or the claim anywhere else, refuses."
    )
    w("")
    exemptions = (register.get("compat_claim") or {}).get("exemptions") if isinstance(register.get("compat_claim"), dict) else []
    w("| File | Line sha256 | Reason |")
    w("|---|---|---|")
    for ex in vdr._as_list(exemptions):
        if isinstance(ex, dict):
            w(f"| {_code(ex.get('file'))} | {_code(str(ex.get('line_sha256'))[:16])} | {_cell(ex.get('reason'))} |")
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description="Render the divergence register, or refuse a stale rendering.")
    ap.add_argument("--check", action="store_true", help="render in memory and refuse drift; write nothing")
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args(argv)
    try:
        ctx = vdr.load_context()
    except vdr.Unreadable as exc:
        print(exc.render(), file=sys.stderr)
        return 2
    text = render(ctx)
    rel = vdr.RENDERED.relative_to(vdr.ROOT).as_posix()
    if args.check:
        if ctx["rendered"] != text:
            # The validator's own refusal, so the two tools word one state alike:
            # a missing rendering is reported as missing, with no cause given.
            for fnd in vdr.check_render(ctx):
                print(fnd.render(), file=sys.stderr)
            return 1
        if not args.quiet:
            print(f"render_divergence_register ok: {rel} is current against spec/divergence-register.yaml")
        return 0
    with open(vdr.RENDERED, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    if not args.quiet:
        print(f"wrote {rel} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
